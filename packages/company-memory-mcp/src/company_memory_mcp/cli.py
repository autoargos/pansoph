# ---------------------------------------------------------------- secrets and compose


def _load_env() -> dict[str, str]:
    if not STACK_ENV.exists():
        raise CliError("no secrets yet: run `uv run company-memory init`")
    out: dict[str, str] = {}
    for line in STACK_ENV.read_text().splitlines():
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k] = v
    return out


def _write_private(path: Path, text: str, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.parent.chmod(0o700)
    path.write_text(text)
    path.chmod(mode)


def cmd_init(args: argparse.Namespace) -> None:
    if STACK_ENV.exists() and not args.force:
        _say(f"secrets already exist in {SECRETS_DIR.relative_to(REPO)} (use --force to rotate)")
    else:
        values = {name: secrets.token_urlsafe(32) for name in _SECRET_NAMES}
        body = "# Generated by `company-memory init`. LOCAL POC secrets. Never commit.\n"
        body += "".join(f"{k}={v}\n" for k, v in values.items())
        _write_private(STACK_ENV, body)
        _say(f"generated secrets in {STACK_ENV.relative_to(REPO)}")
    _render_realm()
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    STATE_DIR.chmod(0o700)


def _profile() -> ru.RealUserProfile:
    try:
        return ru.load_profile(USERS_LOCAL, USERS_EXAMPLE)
    except (ru.UserConfigError, json.JSONDecodeError) as exc:
        raise CliError(f"{USERS_LOCAL.name}: {exc}") from exc


def _real_passwords(profile: ru.RealUserProfile) -> dict[str, str]:
    stored = json.loads(REAL_PASSWORDS.read_text()) if REAL_PASSWORDS.exists() else {}
    passwords = ru.ensure_passwords(profile, stored)
    if passwords != stored:
        _write_private(REAL_PASSWORDS, json.dumps(passwords, indent=2))
    return passwords


def _render_realm() -> None:
    """Template + generated secrets + the configured real users (if any). Keycloak imports
    it when its container is created (a realm that already exists is not re-imported)."""
    env = _load_env()
    realm = json.loads(REALM_TEMPLATE.read_text())
    realm = {k: v for k, v in realm.items() if not k.startswith("_")}
    rendered = json.dumps(realm, indent=2)
    for name, value in env.items():
        rendered = rendered.replace("${" + name + "}", value)
    if "${" in rendered:
        raise CliError("realm template has an unfilled placeholder")
    profile = _profile()
    try:
        merged = ru.merge_into_realm(json.loads(rendered), profile, _real_passwords(profile))
    except ru.UserConfigError as exc:
        raise CliError(str(exc)) from exc
    # Readable by the Keycloak container through the bind mount; the directory is 0700.
    _write_private(REALM_OUT, json.dumps(merged, indent=2) + "\n", mode=0o644)
    _say(
        f"rendered realm to {REALM_OUT.relative_to(REPO)} "
        f"({len(profile.users)} configured real user(s), tenant {profile.tenant})"
    )


def _compose(*args: str, check: bool = True, capture: bool = False) -> str:
    cmd = [
        "docker",
        "compose",
        "-f",
        str(DEPLOY / "compose.yaml"),
        "--env-file",
        str(STACK_ENV),
        *args,
    ]
    res = subprocess.run(cmd, check=False, text=True, capture_output=capture)  # noqa: S603
    if check and res.returncode != 0:
        raise CliError(f"docker compose {' '.join(args)} failed ({res.returncode})")
    return res.stdout if capture else ""


def cmd_up(args: argparse.Namespace) -> None:
    if not STACK_ENV.exists():
        cmd_init(argparse.Namespace(force=False))
    _say("starting the Company Memory stack (first run builds the image and downloads a")
