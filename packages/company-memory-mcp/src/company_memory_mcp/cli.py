async def _mcp_call(
    user: str | None, tool: str, arguments: dict[str, Any], *, token: str | None = None
) -> dict[str, Any]:
    from mcp import ClientSession
    from mcp.client.streamable_http import streamable_http_client

    bearer = token or (_access_token(user) if user else None)
    headers = {"Authorization": f"Bearer {bearer}"} if bearer else {}
    async with httpx.AsyncClient(headers=headers, timeout=30.0) as client:
        async with streamable_http_client(
            MCP_URL, http_client=client, terminate_on_close=False
        ) as (
            read,
            write,
            _,
        ):
            async with ClientSession(read, write) as session:
                await session.initialize()
                result = await session.call_tool(tool, arguments)
    data = result.structuredContent or json.loads(
        "".join(getattr(c, "text", "") for c in result.content)
    )
    if set(data) == {"result"} and isinstance(data["result"], dict):
        data = data["result"]
    return dict(data)


