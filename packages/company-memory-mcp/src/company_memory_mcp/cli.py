def cmd_audit(args: argparse.Namespace) -> None:
    logs = _compose("logs", "--no-log-prefix", "--no-color", "agora", "mcp", capture=True)
    events = []
    for line in logs.splitlines():
        if line.startswith("AUDIT "):
            try:
                events.append(json.loads(line[len("AUDIT ") :]))
            except json.JSONDecodeError:
                continue
    events.sort(key=lambda e: e.get("ts", ""))
    for e in events[-args.n :]:
        what = e.get("tool") or e["action"]
        returned = e.get("returned", e.get("doc_ids", e.get("results", "")))
        if e.get("action") == "mcp_knowledge_write":
            returned = (
                f"{e.get('source_id', '')} scope={e.get('requested_scope', '-')} "
                f"acl={json.dumps(e.get('effective_acl', {}))} {e.get('reason', '')}"
            ).strip()
        _say(
            f"{e.get('ts', '')[11:19]}  {e.get('actor', ''):<28} {what:<32} "
            f"tenant={e.get('tenant', '') or '-'} {e.get('decision', '')} {returned}"
        )


