def main(argv: list[str] | None = None) -> None:
    args = _parser().parse_args(argv)
    name = f"cmd_{args.cmd.replace('-', '_')}"
    if name in globals():
        handler = globals()[name]
    else:
        # Real-user and live-demo commands live in their own modules (they use helpers here).
        from . import cli_demo, cli_real

        handler = getattr(cli_real, name, None) or getattr(cli_demo, name)
    try:
        handler(args)
    except CliError as exc:
        sys.stderr.write(f"error: {exc}\n")
        raise SystemExit(2) from exc


if __name__ == "__main__":
    main()
