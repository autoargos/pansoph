"""`company-memory`: the local Company Memory demo CLI. LOCAL POC ONLY, synthetic data.

Run from the repo with `uv run company-memory <command>` (after `uv sync --all-packages`).
Secrets and tokens live under deploy/company-memory/.secrets and .state (gitignored,
owner only) and are never printed. See docs/company-memory/DEMO.md.

User login uses the OAuth password grant against a dedicated public client that exists
only in the local POC realm, with generated per user passwords. That is a documented
POC shortcut for a scripted, repeatable demo (a pilot uses authorization code with PKCE
or the device flow). It is still a real IdP login: agora and the MCP validate every
token's signature, issuer, audience, and expiry, and read groups from userinfo.
"""

