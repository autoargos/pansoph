# ---------------------------------------------------------------- live verification


class _Checks:
    def __init__(self) -> None:
        self.failed = 0

    def check(self, ok: bool, label: str) -> None:
        self.failed += 0 if ok else 1
        _say(f"  {'PASS' if ok else 'FAIL'}  {label}")


async def _verify() -> int:
    c = _Checks()
    # Transport authentication.
    init = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-06-18",
            "capabilities": {},
            "clientInfo": {"name": "verify", "version": "0"},
        },
    }
    accept = {"Accept": "application/json, text/event-stream"}
    async with httpx.AsyncClient(timeout=15.0) as http:
        r1 = await http.post(MCP_URL, json=init, headers=accept)
        r2 = await http.post(MCP_URL, json=init, headers={**accept, "Authorization": "Bearer x"})
    c.check(r1.status_code == 401, "MCP without a token is rejected (401)")
    c.check(r2.status_code == 401, "MCP with an invalid token is rejected (401)")
    # The same query, four users, four different authorized results; REST agrees.
    for user in USERS:
        found = await _mcp_call(
            user, "search_company_memory", {"query": dd.DEMO_QUERY, "limit": 20}
        )
        # Corpus sources only: manual knowledge added during the demo (step 11) may also
        # appear for users allowed to read it, and is covered by the marker check below.
        got = {
            dd.stem_of(r["source_id"])
            for r in found["results"]
            if r["source_id"].startswith(f"{dd.CONNECTOR}:")
        }
        c.check(got == dd.EXPECTED[user], f"{user}: sees exactly {sorted(dd.EXPECTED[user])}")
        text = json.dumps(found)
        leaked = [m for m in dd.FORBIDDEN[user] if m in text]
        c.check(not leaked, f"{user}: no restricted marker in the MCP response {leaked or ''}")
        evidence = await _mcp_call(
            user, "search_company_memory_evidence", {"query": dd.DEMO_QUERY, "limit": 20}
        )
        async with httpx.AsyncClient(timeout=30.0) as http:
            rest_resp = await http.post(
                f"{AGORA}/api/search",
                json={"query": dd.DEMO_QUERY, "final_k": 20},
                headers={"Authorization": f"Bearer {_access_token(user)}"},
            )
        rest = rest_resp.json()
        c.check(
            {x["source_id"] for x in evidence["chunks"]} == {x["doc_id"] for x in rest["results"]},
            f"{user}: MCP evidence and REST /api/search return the same sources",
        )
    # A document id is not authorization; denied equals nonexistent.
    denied = await _mcp_call(
        "alice",
        "get_company_memory_source",
        {"source_id": dd.doc_id("leadership-fy27-financial-plan")},
    )
    missing = await _mcp_call(
        "alice", "get_company_memory_source", {"source_id": dd.doc_id("nope")}
    )
    c.check(
        "error" in denied
        and denied.get("error") == missing.get("error")
        and "7.3M" not in str(denied),
        "alice cannot read the leadership document by id (same answer as nonexistent)",
    )
    # Revocation: remove alice from project-atlas, same token, same query.
    atlas = dd.doc_id("atlas-adr-007-authentication")
    q = {"query": dd.REVOCATION_QUERY, "limit": 10}
    before = await _mcp_call("alice", "search_company_memory", q)
    c.check(atlas in {r["source_id"] for r in before["results"]}, "alice sees Atlas ADR-007 before")
    with _kc_admin() as kc:
        _set_membership(kc, dd.REVOCATION_USER, dd.REVOCATION_GROUP, member=False)
    try:
        after = await _mcp_call("alice", "search_company_memory", q)
        text = json.dumps(after)
        c.check(
            not any(m in text for m in dd.MARKERS["atlas"]) and "atlas-adr-007" not in text,
            "after revocation: no Atlas content, citation, or id for alice (same token)",
        )
        src = await _mcp_call("alice", "get_company_memory_source", {"source_id": atlas})
        c.check("error" in src, "after revocation: get_company_memory_source denies Atlas")
    finally:
        with _kc_admin() as kc:
            _set_membership(kc, dd.REVOCATION_USER, dd.REVOCATION_GROUP, member=True)
    restored = await _mcp_call("alice", "search_company_memory", q)
    c.check(atlas in {r["source_id"] for r in restored["results"]}, "re-granted: Atlas is back")
    await _verify_knowledge(c)
    return c.failed


async def _verify_knowledge(c: _Checks) -> None:
    """Manual knowledge through the MCP write tool: default privacy, publish grants, the
    same read authorization as every source, grant, revoke, and delete. Uses its own
    probe documents (unique per run) and deletes them, so the demo document is untouched."""
    probe = f"VERIFY-PROBE-{secrets.token_hex(4).upper()}"
    q = {"query": f"verification probe {probe}", "limit": 10}

    def ids(found: dict[str, Any]) -> set[str]:
        return {r["source_id"] for r in found.get("results", [])}

    private = await _mcp_call(
        "alice",
        "add_company_memory_knowledge",
        {"title": f"Private probe {probe}", "content": f"Alice private note {probe}."},
    )
    c.check(
        private.get("status") == "added" and private.get("scope") == "private",
        "alice adds knowledge without a scope: stored as private",
    )
    shared = await _mcp_call(
        "alice",
        "add_company_memory_knowledge",
        {
            "title": f"Atlas probe {probe}",
            "content": f"Atlas shared note {probe}.",
            "scope": "project-atlas",
        },
    )
    c.check(shared.get("status") == "added", "alice publishes to project-atlas (publisher grant)")
    pid, sid = private.get("source_id", ""), shared.get("source_id", "")
    try:
        denied = await _mcp_call(
            "alice",
            "add_company_memory_knowledge",
            {"title": f"x {probe}", "content": "x", "scope": "leadership"},
        )
        c.check(denied.get("status") == "denied", "alice cannot publish to leadership")
        bob_pub = await _mcp_call(
            "bob",
            "add_company_memory_knowledge",
            {"title": f"x {probe}", "content": "x", "scope": "project-atlas"},
        )
        c.check(bob_pub.get("status") == "denied", "bob cannot publish to project-atlas")
        c.check(
            {pid, sid} <= ids(await _mcp_call("alice", "search_company_memory", q)),
            "alice retrieves both of her new documents",
        )
        bob = await _mcp_call("bob", "search_company_memory", q)
        c.check(
            not ({pid, sid} & ids(bob)) and probe not in json.dumps(bob),
            "bob retrieves neither (no id, title, or text)",
        )
        src = await _mcp_call("bob", "get_company_memory_source", {"source_id": sid})
        c.check(src.get("error") == _not_found(), "bob cannot read the Atlas probe by id")
        with _kc_admin() as kc:
            _set_membership(kc, "bob", "project-atlas", member=True)
        try:
            granted = ids(await _mcp_call("bob", "search_company_memory", q))
            c.check(sid in granted and pid not in granted, "granted bob: Atlas probe only")
            again = await _mcp_call(
                "bob",
                "add_company_memory_knowledge",
                {"title": f"x {probe}", "content": "x", "scope": "project-atlas"},
            )
            c.check(again.get("status") == "denied", "reading Atlas does not let bob publish")
        finally:
            with _kc_admin() as kc:
                _set_membership(kc, "bob", "project-atlas", member=False)
        c.check(
            sid not in ids(await _mcp_call("bob", "search_company_memory", q)),
            "revoked bob: the Atlas probe is gone on the next query",
        )
    finally:
        for source_id in (pid, sid):
            if source_id:
                await _mcp_call(
                    "alice", "delete_company_memory_knowledge", {"source_id": source_id}
                )
    after = await _mcp_call("alice", "search_company_memory", q)
    c.check(
        not ({pid, sid} & ids(after)) and probe not in json.dumps(after),
        "deleted: neither probe is retrievable, even by alice",
    )


